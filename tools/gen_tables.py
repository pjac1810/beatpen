"""Generate src/tables.h for BEATPEN (integers only on the FM-1).

FILT_G[i]  TPT one-pole coefficient G = g / (1 + g), g = tan(pi fc / fs), Q16; fc 20 Hz .. 16 kHz, exponential
"""
import math
from pathlib import Path

FS = 44100
OUT = Path(__file__).resolve().parents[1] / "src" / "tables.h"
vals = []
for i in range(1024):
  fc = 20.0 * (16000.0 / 20.0) ** (i / 1023)
  g = math.tan(math.pi * fc / FS)
  vals.append(round(g / (1 + g) * 65536))
rows = ["  " + ", ".join(f"{v}u" for v in vals[i : i + 16]) + "," for i in range(0, 1024, 16)]
OUT.write_text(
  "/* SPDX-License-Identifier: GPL-3.0-only */\n/* generated by tools/gen_tables.py: do not edit */\n"
  "#ifndef BEATPEN_TABLES_H\n#define BEATPEN_TABLES_H\n#include <stdint.h>\n\n"
  "static const uint16_t FILT_G[1024] = {\n" + "\n".join(rows) + "\n};\n\n#endif\n"
)
print("wrote", OUT)
